-- 20260712000100_exam_format · 考试成绩自动判断需要"开卷/闭卷"(PM 2026-07-12)
-- 背景:大纲原文考试及格线按两条轴分档——① 共修出勤总次数是否达到93次
--   （达到→合格30分；达不到→按②）② 开卷72分 / 闭卷60分。①可从 study_records
--   现有数据实时算,②这张表原本没有任何字段能推断,故加这一列。
-- 明确不做(范围边界,已向PM说明):
--   · "本届第一次考试报名时年满60岁免考"——本库无生日/年龄字段,加会牵涉个人
--     信息收集,超出这次"暂时"范围,不在此加。
--   · "达不到93次的可改考2次、每次合格30分"这条替代路径——需要跨行聚合当前次
--     考试之外的历史记录,判定逻辑更复杂,这次先按"单次考试对单一分数线"算。
--   以上两条边界情形,is_pass 会按①②正常算出的结果为准,不代表该学员真实免考/
--   走了替代路径;如需要,再录一条 exam_grades(notes 写明缘由)即可(同现有
--   "无编辑、只加新记录"惯例,不改历史行)。
-- ============================================================

ALTER TABLE exam_grades
  ADD COLUMN exam_format text CHECK (exam_format IS NULL OR exam_format IN ('open', 'closed'));

COMMENT ON COLUMN exam_grades.exam_format IS '开卷open/闭卷closed;仅共勤出勤总次数<93时决定合格线(72/60),≥93时不影响(合格线恒30)';
